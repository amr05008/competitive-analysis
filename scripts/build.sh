#!/bin/sh
# Pull the report contract from the public agent-skills checkout and stamp it.
# references/report-template.md in this repo is generated; edit the source in
# amr05008/agent-skills (competitive-analysis/references/report-template.md).
set -eu
SRC="${AGENT_SKILLS_DIR:-$HOME/repos/agent-skills}"
F="$SRC/competitive-analysis/references/report-template.md"
[ -f "$F" ] || { echo "build: $F not found" >&2; exit 3; }
SHA=$(git -C "$SRC" rev-parse --short HEAD)
OUT="$(dirname "$0")/../skills/teardown/references/report-template.md"
{
  echo "<!-- Generated by scripts/build.sh from amr05008/agent-skills@$SHA. Do not edit here. -->"
  echo
  cat "$F"
} > "$OUT"
echo "build: wrote $OUT from agent-skills@$SHA"
